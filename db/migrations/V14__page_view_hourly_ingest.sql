-- =====================================================================
-- V14 — 시간별 조회수 적재 원장 (WP-199)
-- =====================================================================
--
-- 🔴 왜 필요한가 — "조회수 0" 과 "아직 안 옴" 이 구분되지 않는다
--
--   위키미디어 시간별 덤프는 **조회수 0 인 문서를 아예 싣지 않는다.** 그래서
--   `page_view_hourly` 에 행이 없는 것이 두 가지를 동시에 뜻한다:
--
--       (1) 그 시간 원본이 아직 안 왔다        → 대기 유지가 맞다
--       (2) 원본은 왔는데 그 문서가 0회였다    → 폐기가 맞다
--
--   `spike/recheck.py` 는 (1)로만 해석한다. 그래서 0회 문서가 영원히 대기로 남고,
--   재판정이 가장 오래된 시간부터 도는 구조라 **큐가 맨 앞에서 막힌다.**
--
--   2026-09-22 실측: 앞 6시간에 0회 문서 500건이 남아 뒤의 53,982건이 통째로
--   굶었다. 36시간 만료로 언젠가 풀리지만 그건 "판정했다" 가 아니라 "포기했다" 다
--   — 조회수 0 이라는 판정 가능한 사실이 있었는데 못 쓴 것이다.
--
--   ⚠️ 명세 §3.2 12번이 요구하는 "장애와 정상 0건 구분" 을 **반대 방향으로** 틀린
--   경우다. 정상 0을 미도착으로 오인한다.
--
-- 🔴 왜 추론으로 안 되나
--   "그 ts_hour 에 행이 하나라도 있으면 적재된 것" 으로 추론할 수도 있다. 실제로
--   2026-09-22 임시 조치는 그렇게 했다. 하지만 LIVE 적재는 **대기 목록의 문서만**
--   선택적으로 받는다(전수는 시간당 149만 행이라 못 한다). 그 시간 후보가 전부
--   0회면 행이 0개가 되고, 그러면 "적재 안 됨" 으로 오판한다. 드물지만 조용하다.
--   그래서 추론하지 않고 사실을 적는다.
--
-- ⚠️ V12 는 팀원 3(page_asof_links), V13 은 llm_daily_usage(-191)다. V14 가 다음이다.

CREATE TABLE page_view_hourly_ingest (
    wiki        TEXT        NOT NULL,
    -- 윈도우 **시작** 정각 UTC. page_view_hourly.ts_hour 와 같은 축이다.
    -- 🔴 파일명 시각이 아니다 — 파일명은 윈도우 끝이다 (WP-127).
    ts_hour     TIMESTAMPTZ NOT NULL,
    -- 이 시간에 실제로 쓴 행 수. 0 도 정상이다("그 시간 후보가 전부 0회였다").
    -- 값 자체보다 **행의 존재**가 신호다.
    rows        INTEGER     NOT NULL DEFAULT 0 CHECK (rows >= 0),
    ingested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (wiki, ts_hour)
);

COMMENT ON TABLE page_view_hourly_ingest IS
    '시간별 조회수 원본을 실제로 받아 적재한 (wiki, 시간) 원장 (WP-199). '
    '🔴 이 표에 행이 있으면 그 시간은 "도착했다" 는 뜻이고, 그 시간의 문서에 '
    'page_view_hourly 행이 없으면 "조회수 0" 으로 판정해야 한다. 행이 없으면 '
    '아직 미도착이므로 대기를 유지한다. 둘을 구분하는 것이 이 표의 유일한 목적이다.';

COMMENT ON COLUMN page_view_hourly_ingest.rows IS
    '그 적재에서 page_view_hourly 에 쓴 행 수. 0 이어도 적재는 완료된 것이다 — '
    'LIVE 는 대기 목록의 문서만 선택적으로 받으므로 후보가 전부 0회면 0행이 된다. '
    '⚠️ 그래서 "rows > 0" 을 적재 완료 조건으로 쓰면 안 된다. 행의 존재가 조건이다.';
