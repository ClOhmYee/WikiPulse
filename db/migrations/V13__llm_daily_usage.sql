--   (-182)과 번호가 겹쳐 있다. 그쪽을 V12 로 리넘버하기로 전달했으므로 여기는
--   V13 을 쓴다. 같은 번호 두 개는 적용 도구가 거부하고, 우리 두 적용 경로
--   (`db/apply_migrations.py` 정수 정렬 / Docker 파일명 정렬)가 서로 다른 순서로
--   적용할 수 있다 — -117 에서 V5 로 이미 겪었다.
--
-- 왜 필요한가
--   `top-per-snapshot`(-165·-176)은 **스냅샷당** 상한이고 `summary.max-attempts`
--   (-182)는 **클러스터당** 상한이다. **하루 총량을 묶는 것은 없었다.**
--
--   2026-09-22 실측: 51분에 5,414 크레딧이 나갔다(-182 무한 재시도). 그 경로는
--   막혔지만, 총량 상한이 있었으면 5,414 가 아니라 상한만큼만 샜다.
--
-- 왜 프로세스 메모리가 아닌가
--   🔴 백엔드가 재배포되면 그 날 예산이 초기화된다. develop 머지가 곧 배포라
--   오늘만 해도 3번 돌았다. 카운터가 메모리에 있으면 배포할 때마다 상한이 풀린다.
--
-- 왜 크레딧이 아니라 호출 수인가
--   크레딧으로 묶으려면 GATEWAY `key-info` 를 주기적으로 읽어야 하는데, 그 값은
--   지연되고 소액 호출은 델타가 0 으로 반올림된다(-170 실측). 호출 수는 우리가
--   원자적으로 셀 수 있는 값이라 상한이 정확히 동작한다.
--   ⚠️ 대신 단가는 모델마다 다르다 — 환산은 설정 주석에 적는다
--   (2026-09-21 -170 실측: 검증 nano 호출당 약 9 · 요약 1회 41~62).

CREATE TABLE llm_daily_usage (
    -- 🔴 UTC 날짜다. DB 서버 시간대에 기대지 않는다 — 리셋 경계가 환경마다
    --    달라지면 "하루"의 뜻이 갈린다. 쓰는 쪽이 (now() AT TIME ZONE 'UTC')::date 를 준다.
    usage_date DATE    NOT NULL,
    -- 요약과 검증을 나눠 센다. 한 통으로 묶으면 검증이 요약을 굶긴다 — 이슈 하나당
    -- 검증은 후보 수만큼 호출되고 요약은 1회다.
    kind       TEXT    NOT NULL CHECK (kind IN ('summary', 'verification')),
    calls      INTEGER NOT NULL DEFAULT 0 CHECK (calls >= 0),
    PRIMARY KEY (usage_date, kind)
);

COMMENT ON TABLE llm_daily_usage IS
    'GATEWAY LLM 호출의 UTC 일자별 누적 수 (WP-191). 상한 판정과 사후 분석에 쓴다. '
    '🔴 증가와 상한 검사를 한 문장으로 한다 — 나누면 폴러 둘이 같은 순간에 통과한다.';

COMMENT ON COLUMN llm_daily_usage.kind IS
    'summary(이슈 요약, 클러스터당 1회) / verification(종목 검증, 후보당 1회). '
    '나눠 세는 이유는 호출 수가 자릿수로 다르기 때문이다 — 한 예산을 공유하면 '
    '검증이 먼저 다 쓰고 요약이 영영 안 돈다.';
