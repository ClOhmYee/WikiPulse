-- =====================================================================
-- V15 — 시간별 조회수의 모바일 몫 (WP-210)
-- =====================================================================
--
-- 왜 필요한가
--   `other/pageviews` 시간별 덤프는 데스크톱(`en`)과 모바일(`en.m`)을 **별개 행**으로
--   준다. 지금까지 `batch/pageview_hourly.aggregate()` 가 둘을 합산하고 구분을 버렸다.
--
--   그 비율이 **봇 트래픽과 실제 사건을 가르는 유일한 신호**다 (2026-09-22 실측):
--
--     Roblox            2026-08-10   478만 조회(674배)   모바일  0.1%   ← 봇
--     Google            2026-08-18   24.5만              모바일  4.0%   ← 봇
--     Air India 171     2025-06-12   65.7만              모바일 63.1%   ← 골든데이 정답
--     Moderna           2026-08-19   6,893 (60배)        모바일 52.1%   ← 실제 사건
--
--   겹치는 구간이 없다(사건 52~64% vs 봇 0.1~4%). 근거·재현은
--   `ai/spec-evidence/gate-review/RESULT.md`.
--
-- 🔴 여기서 안 받으면 다시 얻는 값이 아니다
--   같은 파일 안에 이미 있는 값이라 적재 때 남기면 공짜다. 버린 뒤에 필요해지면
--   문서마다 AQS per-article 을 때려야 하고, 그건 동시 8요청에서 429 가 난다
--   (같은 조사에서 1,868건 중 1,665건이 스로틀링으로 빈 응답이었다).
--
-- ⚠️ 부분집합이지 별개 축이 아니다
--   `mobile_views <= views` 다. `views` 는 데스크톱+모바일 합이고 여기서 빼지 않는다.
--   빼는 쪽으로 오해하면 조회수가 조용히 절반이 된다.
--
-- ⚠️ 기존 행은 0 으로 채워진다 — "모바일이 0이었다"가 아니라 **"안 재고 지나갔다"** 다.
--   V15 이전 적재분(2026-09-22 기준 116,097행)에 이 값으로 봇 판정을 걸면 전부 봇이
--   된다. 판정하는 쪽은 `measured_at` 이 아니라 **`ts_hour` 가 이 마이그레이션 적용
--   시점 이후인지**로 가르거나, 그 구간을 다시 적재해서 쓴다.

ALTER TABLE page_view_hourly
    ADD COLUMN mobile_views INTEGER NOT NULL DEFAULT 0
        CHECK (mobile_views >= 0);

COMMENT ON COLUMN page_view_hourly.mobile_views IS
    'views 중 모바일웹(`en.m`) 몫. views 에 포함된 부분집합이라 빼지 않는다 '
    '(WP-210). 봇 트래픽은 데스크톱 단일 채널로 와서 이 비율이 0에 가깝다 — '
    '실측 사건 52~64% vs 봇 0.1~4%. '
    '⚠️ V15 이전 적재분은 0 이며 그것은 "모바일 0" 이 아니라 "미측정" 이다.';
